package com.dileep.ailearning.production.dto;

/**
 * Snapshot of production operational metrics for LLM calls (Module 7).
 *
 * @param totalRequests          total chat requests processed
 * @param exactCacheHits         requests served from Tier-1 SHA-256 exact cache
 * @param semanticCacheHits      requests served from Tier-2 pgvector semantic cache
 * @param cacheMisses            requests routed to model inference
 * @param cacheHitRatio          percentage of requests served from cache
 * @param fallbackCount          requests where primary model failed and fallback was used
 * @param promptTokensServed     total prompt tokens sent to model
 * @param responseTokensServed   total response tokens generated by model
 * @param promptTokensSaved      prompt tokens saved by cache hits
 * @param responseTokensSaved    response tokens saved by cache hits
 * @param avgTtftMs              average time-to-first-token in milliseconds
 * @param avgTpotMs              average time-per-output-token in milliseconds
 */
public record ProductionMetricsSnapshot(
        long totalRequests,
        long exactCacheHits,
        long semanticCacheHits,
        long cacheMisses,
        double cacheHitRatio,
        long fallbackCount,
        long promptTokensServed,
        long responseTokensServed,
        long promptTokensSaved,
        long responseTokensSaved,
        double avgTtftMs,
        double avgTpotMs
) {
}
